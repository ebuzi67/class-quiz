def svg(s):
    """학습지용 고정 크기 SVG를 화면 폭에 맞게 줄어드는 SVG로 바꿔요."""
    # 태블릿에서는 학습지보다 1.5배까지 크게 보여요.
    return re.sub(r'<svg viewBox="([^"]+)" width="(\d+)" height="(\d+)"',
                  lambda m: f'<svg viewBox="{m[1]}" style="width:100%;max-width:{int(int(m[2]) * 1.5)}px;height:auto"', s)


def num(fig, q, answer, unit, explain, hint):
    return {"type": "num", "fig": svg(fig) if fig else "", "q": q, "answer": answer, "unit": unit, "explain": explain, "hint": hint}


def choice(fig, q, choices, answer, explain, hint):
    return {"type": "choice", "fig": svg(fig) if fig else "", "q": q, "choices": choices, "answer": choices.index(answer), "explain": explain, "hint": hint}


def ox(q, answer, explain):
    return {"type": "choice", "fig": "", "q": q, "choices": ["O", "X"], "answer": 0 if answer == "O" else 1, "explain": explain,
            "hint": "개념 보기에서 배운 내용을 다시 떠올려 보세요."}


