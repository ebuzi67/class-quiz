const head = (a, b, color = C.ink) => {
  const d = unit(sub(b, a)), n = [-d[1], d[0]];
  const p1 = add(sub(b, mul(d, 12)), mul(n, 6)), p2 = sub(sub(b, mul(d, 12)), mul(n, 6));
  return `<polygon points="${b} ${p1} ${p2}" fill="${color}"/>`;
};
