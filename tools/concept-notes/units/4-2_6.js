const { C, svg, poly, line, text, label, cap, xMark, W, H, regPts, tick, rightAngle, hl } = E;

const box = (x, y, w, h) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="10" fill="#fff8d6" stroke="#e6cf6a"/>`;
const diagonals = (p, color = C.pink) => {
  let s = ''; const n = p.length;
  for (let i = 0; i < n; i++) for (let j = i + 2; j < n; j++) { if (i === 0 && j === n - 1) continue; s += line(p[i], p[j], { stroke: color, sw: 1.5, dash: '4 3' }); }
  return s;
};
const diagCount = n => n * (n - 3) / 2;

