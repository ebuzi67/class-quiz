const E = require('../engine');
const { C, svg, poly, line, text, label, cap, sub, add, mul, unit, mid, rightAngle, xMark, W, H, tick, arc, hl } = E;

const sideLabel = (a, b, s, out = 1, size = 13, color = '#333') => {
  const m = mid(a, b), d = unit(sub(b, a)), n = [d[1] * out, -d[0] * out];
  const t = add(m, mul(n, 15)); return text(t[0], t[1], s, { size, color });
};
// 삼각형 + 각 표시. ang: 꼭짓점별 [라벨, term?] 또는 null
const tri = (p, { fill = '#eef7f6', ticks = [], ang = [], r = 20, sw = 2.4 } = {}) => {
  let s = poly(p, { fill, stroke: C.ink, sw });
  ticks.forEach(([i, n]) => { s += tick(p[i], p[(i + 1) % 3], n); });
  ang.forEach((a, i) => { if (a) s += arc(p[i], p[(i + 1) % 3], p[(i + 2) % 3], a[2] || r, a[0], { term: a[1], size: 12 }); });
  return s;
};
