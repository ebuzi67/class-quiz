const quad = (p, { fill = '#eef7f6', ticks = [], ang = [], sw = 2.4 } = {}) => {
  let s = poly(p, { fill, stroke: C.ink, sw });
  ticks.forEach(([i, n]) => { s += tick(p[i], p[(i + 1) % 4], n); });
  ang.forEach((a, i) => { if (a) s += arc(p[i], p[(i + 1) % 4], p[(i + 3) % 4], 18, a[0], { term: a[1], size: 12 }); });
  return s;
};

