// 직육면체 겨냥도: 앞면 (x, y, w, h), 깊이 (dx, dy). hidden: 보이지 않는 모서리 점선
function cuboid(x, y, w, h, dx, dy, { front = '#eef7f6', top = '#dcefed', side = '#cfe6e3', hidden = true, sw = 2.2 } = {}) {
  const A = [x, y + h], B = [x + w, y + h], Cc = [x + w, y], D = [x, y];
  const A2 = [A[0] + dx, A[1] - dy], B2 = [B[0] + dx, B[1] - dy], C2 = [Cc[0] + dx, Cc[1] - dy], D2 = [D[0] + dx, D[1] - dy];
  let s = poly([A, B, Cc, D], { fill: front, stroke: 'none' }) + poly([D, Cc, C2, D2], { fill: top, stroke: 'none' }) + poly([B, B2, C2, Cc], { fill: side, stroke: 'none' });
  for (const [p, q] of [[A, B], [B, Cc], [Cc, D], [D, A], [D, D2], [Cc, C2], [B, B2], [D2, C2], [C2, B2]]) s += line(p, q, { sw });
  if (hidden) for (const [p, q] of [[A, A2], [A2, B2], [A2, D2]]) s += line(p, q, { sw: 1.6, dash: '5 4', stroke: '#666' });
  return { s, v: { A, B, C: Cc, D, A2, B2, C2, D2 } };
}

